"""Compositional generalisation on the 4-variable data (results/compositional.md).

    python -m tact.robustness.compositional      # generates data_ext and the refill pool data_ext_pool if missing

Held-out combinations: (emotion = angry, day = Saturday) and (emotion = happy, location = office).
  * "hole" training set: every training scenario with either combination is removed from data_ext's 350 training scenarios and the
    same number of scenarios is drawn from a fresh pool generated by the same generator (seed 43), so that N = 350 is kept;
    the validation set is filtered the same way (not refilled), so that early stopping never sees a held-out combination;
  * "normal" training set: data_ext's training scenarios (the combinations occur) - the upper reference;
  * test: 30 constructed scenarios per combination, topics covered in turn (every topic at least twice), the time of day balanced,
    phrasings 1 / 2 only, clean labels from the config formula with the office factor; identical for both training conditions.
Methods: A (policy), B (argmax of the reward model), C (tabular, key (topic, emotion, day, time, location), fallback to the (topic, action)
mean, then the global mean), Ct (same, keyed by the question text). Five seeds; same seeds in both conditions.
"""
import os
import subprocess
import sys

import numpy as np
import pandas as pd

from tact.decision import budget as B
from tact.core.generate_dataset import QUESTIONS, availability
from tact.reward.grid_eval import TOPICS
from tact.core.model import CONFIG, EMOTIONS, RESULTS_DIR, ROOT, FrozenBert, get_device
from tact.core.plots import is_habit, necessity

DAYS, TIMES = CONFIG["days"], CONFIG["times"]
CTX = ("emotion", "day", "time", "location")
COMBOS = {"angry_sat": "(angry, Saturday)", "happy_office": "(happy, office)"}
COLS = ["id", "cand", "question", "topic", "phrasing", "emotion", "day", "day_name", "time", "time_name", "location", "necessity",
        "receptiveness", "score_clean", "score", "habit_hit"]


def ensure(ddir, args):
    path = os.path.join(ROOT, ddir)
    if not os.path.exists(os.path.join(path, "train.csv")):
        subprocess.run([sys.executable, "-m", "tact.core.generate_dataset", *args, "--with-act", "--with-location", "--outdir", path],
                       check=True, cwd=ROOT, stdout=subprocess.DEVNULL)
    return path


def held(df):
    """Scenario-level mask of the held-out combinations, for a long-format frame (use the ask rows)."""
    return ((df.emotion == "angry") & (df.day == 5)) | ((df.emotion == "happy") & (df.location == "office"))


def build_test(seed=2024):
    rng = np.random.default_rng(seed)
    rows, k = [], 0
    for combo in COMBOS:
        topics = list(TOPICS) * 2 + list(rng.choice(TOPICS, 6, replace=False))
        topics = [topics[i] for i in rng.permutation(30)]
        times = [int(t) for t in rng.permutation([0] * 10 + [1] * 10 + [2] * 10)]
        for i in range(30):
            t, m = topics[i], times[i]
            if combo == "angry_sat":
                e, d, loc = "angry", 5, str(rng.choice(["kitchen", "living_room", "office"]))
            else:
                e, d, loc = "happy", int(rng.integers(7)), "office"
            ph = int(rng.choice([1, 2]))
            nec = necessity(t, d, m)
            rec = CONFIG["valence"][e] * availability(d, m) * (0.3 if loc == "office" else 1.0)
            base = {"id": 50000 + k, "topic": t, "phrasing": ph, "emotion": e, "day": d, "day_name": DAYS[d], "time": m,
                    "time_name": TIMES[m], "location": loc, "necessity": round(nec, 3), "receptiveness": round(rec, 3),
                    "habit_hit": "habit" if is_habit(t, d, m) else "", "combo": combo}
            rows.append({**base, "cand": "ask", "question": QUESTIONS[t][ph - 1], "score_clean": round(nec * rec, 3), "score": round(nec * rec, 3)})
            rows.append({**base, "cand": "act", "question": B.ACT_TEXT, "phrasing": 0, "score_clean": round(1 - nec, 3), "score": round(1 - nec, 3)})
            k += 1
    full = pd.DataFrame(rows)
    return full[COLS], full[full.cand == "ask"].combo.values


def build_dirs():
    ext = ensure("data_ext", ["--n", "500", "--seed", "42"])
    pool = ensure("data_ext_pool", ["--n", "500", "--seed", "43"])
    tr, va = pd.read_csv(os.path.join(ext, "train.csv")), pd.read_csv(os.path.join(ext, "val.csv"))
    pl = pd.read_csv(os.path.join(pool, "train.csv"))
    pl["id"] = pl["id"] + 10000                                  # ids of the refill scenarios must not clash
    ask_tr = tr[tr.cand == "ask"]
    bad_ids = set(ask_tr[held(ask_tr)].id)
    keep = tr[~tr.id.isin(bad_ids)]
    ask_pl = pl[pl.cand == "ask"]
    ok_pool = ask_pl[~held(ask_pl)].id.tolist()[:len(bad_ids)]   # first len(bad_ids) acceptable pool scenarios, in pool order
    hole_tr = pd.concat([keep, pl[pl.id.isin(set(ok_pool))]], ignore_index=True)
    ask_va = va[va.cand == "ask"]
    hole_va = va[~va.id.isin(set(ask_va[held(ask_va)].id))]
    test, combo = build_test()
    info = {"removed_train": len(bad_ids), "refilled": len(ok_pool), "train_total": hole_tr[hole_tr.cand == "ask"].id.nunique(),
            "val_removed": int(held(ask_va).sum()), "val_total": hole_va[hole_va.cand == "ask"].id.nunique(),
            "removed_angry_sat": int(((ask_tr.emotion == "angry") & (ask_tr.day == 5)).sum()),
            "removed_happy_office": int(((ask_tr.emotion == "happy") & (ask_tr.location == "office")).sum()),
            "n_train_normal": ask_tr.id.nunique()}
    for name, (t, v) in {"normal": (tr, va), "hole": (hole_tr, hole_va)}.items():
        d = os.path.join(ROOT, "data_comp", name)
        os.makedirs(d, exist_ok=True)
        t.to_csv(os.path.join(d, "train.csv"), index=False)
        v.to_csv(os.path.join(d, "val.csv"), index=False)
        test.to_csv(os.path.join(d, "test_seen.csv"), index=False)
        test.to_csv(os.path.join(d, "test_unseen.csv"), index=False)   # required by budget.Data; not used here
    assert info["train_total"] == info["n_train_normal"] == 350, info
    return info, combo


def ms(x, nd=3):
    x = np.asarray(x, float)
    return f"{x.mean():.{nd}f} ± {x.std(ddof=1):.{nd}f}"


def main():
    info, combo = build_dirs()
    dev = get_device()
    enc = FrozenBert(dev)
    B.MODEL_KW = {"location_dim": 8}
    rows, dec_store, dec_extra = [], {}, []
    for cond in ("normal", "hole"):
        data = B.Data(enc, dev, data_dir=os.path.join(ROOT, "data_comp", cond))
        ts = data.tests["seen"]
        f = data.f_test["seen"]
        masks = {"all": np.ones(len(ts), bool), "angry_sat": combo == "angry_sat", "happy_office": combo == "happy_office"}
        for seed in B.SEEDS:
            ours = B.Ours(data, seed)
            ours.fit_round(350, seed * 1000 + 350, warm=False)
            a, b = ours.decide(f)
            ra, rc = (x.cpu().numpy() for x in B.reward_scores(ours.rm, f))
            tr_sc = data.sc_train.iloc[:350]
            order = np.random.default_rng([seed, 350]).permutation(350)
            tabs = {"C": B.Tabular("topic", ctx_cols=CTX), "Ct": B.Tabular("question", ctx_cols=CTX)}
            for t in tabs.values():
                t.update(tr_sc, order)
            dec = {"A": a, "B": b}
            lv = {}
            for name, t in tabs.items():
                dec[name], lv[name] = t.decide(ts)
            for m, d in dec.items():
                dec_store[(cond, seed, m)] = d
                for cname, mk in masks.items():
                    sub = ts[mk].reset_index(drop=True)
                    ev = B.evaluate(d[mk], sub)
                    orc = (sub.c_ask.values >= sub.c_act.values)
                    rows.append({"cond": cond, "seed": seed, "method": m, "combo": cname, "regret": ev["regret"], "acc": ev["acc"],
                                 "act_rate": ev["act_rate"], "n_oracle_ask": int(orc.sum()),
                                 "ask_recall": float(d[mk][orc].mean()) if orc.any() else float("nan")})
            for cname, mk in masks.items():
                dec_extra.append({"cond": cond, "seed": seed, "combo": cname,
                                  "ask_mse": float(np.mean((ra[mk] - ts.c_ask.values[mk]) ** 2)),
                                  "ask_bias": float(np.mean(ra[mk] - ts.c_ask.values[mk])),
                                  "act_bias": float(np.mean(rc[mk] - ts.c_act.values[mk])),
                                  "act_abs_err": float(np.mean(np.abs(rc[mk] - ts.c_act.values[mk]))),
                                  "margin_sign_acc": float(np.mean(((ra - rc)[mk] > 0) == (ts.c_ask.values[mk] >= ts.c_act.values[mk]))),
                                  "c_exact": float(lv["C"][0]), "c_topic": float(lv["C"][1]), "c_global": float(lv["C"][2])})
        print(f"[comp] {cond} done", flush=True)
    R, X = pd.DataFrame(rows), pd.DataFrame(dec_extra)
    R.to_csv(os.path.join(RESULTS_DIR, "compositional_runs.csv"), index=False)
    X.to_csv(os.path.join(RESULTS_DIR, "compositional_decomposition.csv"), index=False)

    data = B.Data(enc, dev, data_dir=os.path.join(ROOT, "data_comp", "normal"))
    ts = data.tests["seen"]
    masks = {"all": np.ones(len(ts), bool), "angry_sat": combo == "angry_sat", "happy_office": combo == "happy_office"}
    bl = {c: B.baselines(ts[mk].reset_index(drop=True)) for c, mk in masks.items()}
    names = {"all": "all 60 scenarios", "angry_sat": "(angry, Saturday), 30", "happy_office": "(happy, office), 30"}
    out = ["# Compositional generalisation (`compositional.py`)\n",
           "Data: data_ext (4 context variables). Held-out combinations: (angry, Saturday) and (happy, office). **Hole** training set: "
           f"all training scenarios with either combination were removed ({info['removed_train']} of 350: {info['removed_angry_sat']} "
           f"(angry, Sat) and {info['removed_happy_office']} (happy, office), the two groups are disjoint) and replaced by {info['refilled']} "
           "scenarios from a fresh pool of the same generator (seed 43), so N = 350 as before; the validation set is filtered in the same "
           f"way ({info['val_removed']} of 75 removed, not refilled). **Normal** training set = data_ext's 350 scenarios (the combinations "
           "occur in training): the reference for what the model could do if it had seen them. Test: 30 constructed scenarios per "
           "combination (all 12 topics at least twice, time of day balanced, phrasings 1/2, random remaining context; clean labels from the "
           "config formula), the same 60 scenarios for both conditions. Models: BertScorer + 8-d location embedding for A and B; tabular C "
           "with key (topic, emotion, day, time, location) and the fallback chain; Ct keyed by the question text. 5 seeds, same seeds in "
           "both conditions, no tuning.\n",
           "The main effects remain in the hole training data: angry on the other days, the other emotions on Saturday, happy in the "
           "other locations, the other emotions in the office.\n",
           "## Baselines on the test scenarios\n", "| scenarios | always-ask regret | never-ask regret | oracle acts |", "|---|---|---|---|"]
    for c in masks:
        b = bl[c]
        out.append(f"| {names[c]} | {b['always_ask']['regret']:.3f} | {b['never_ask']['regret']:.3f} | {b['oracle']['act_rate']:.0%} |")
    out += ["\n## Regret and accuracy on the held-out combinations (mean ± std over 5 seeds)\n",
            "Hole = trained without the combinations; normal = trained with them (upper reference). Gap = hole − normal, paired by seed "
            "(positive regret gap / negative accuracy gap = worse without the combination).\n",
            "| method | scenarios | regret, normal | regret, hole | gap | accuracy, normal | accuracy, hole | gap |", "|---|---|---|---|---|---|---|---|"]
    for m, nm in (("A", "A policy"), ("B", "B argmax"), ("C", "C tabular"), ("Ct", "Ct tabular (text key)")):
        for c in masks:
            g = lambda cond, col: R[(R.method == m) & (R.combo == c) & (R.cond == cond)].sort_values("seed")[col].values
            rg, ag = g("hole", "regret") - g("normal", "regret"), g("hole", "acc") - g("normal", "acc")
            out.append(f"| {nm} | {names[c]} | {ms(g('normal', 'regret'))} | {ms(g('hole', 'regret'))} | {rg.mean():+.3f} ± {rg.std(ddof=1):.3f} | "
                       f"{ms(g('normal', 'acc'), 2)} | {ms(g('hole', 'acc'), 2)} | {ag.mean():+.2f} ± {ag.std(ddof=1):.2f} |")
    nv = bl["all"]["never_ask"]["regret"]
    better = []
    for m in ("A", "B", "C", "Ct"):
        for cond in ("normal", "hole"):
            r_ = R[(R.method == m) & (R.combo == "all") & (R.cond == cond)].regret.mean()
            better.append(f"{m}/{cond} {r_:.3f}")
    out += [f"\n**Reading the decision metrics.** On these 60 scenarios the oracle acts in {bl['all']['oracle']['act_rate']:.0%} of the cases and "
            f"never-ask has a regret of only {nv:.3f} (accuracy {bl['all']['never_ask']['acc']:.2f}). Mean regret of the methods over all 60 scenarios: "
            + ", ".join(better) + ". **No method is better than never-ask, in either condition**, so regret and accuracy cannot separate "
            "composition from the trivial 'act' default here; the ask-score error of the reward model (next section) and the ask recall "
            "below are the more diagnostic quantities.\n",
            "### Ask recall: share of the scenarios in which the oracle asks where the method asks\n",
            "| method | scenarios (oracle asks in) | recall, normal | recall, hole |", "|---|---|---|---|"]
    for m, nm in (("A", "A policy"), ("B", "B argmax"), ("C", "C tabular"), ("Ct", "Ct tabular (text key)")):
        for c in masks:
            sub_ = ts[masks[c]]
            n_or = int((sub_.c_ask.values >= sub_.c_act.values).sum())
            g = lambda cond: R[(R.method == m) & (R.combo == c) & (R.cond == cond)].ask_recall.values
            out.append(f"| {nm} | {names[c]} ({n_or}) | {ms(g('normal'), 2)} | {ms(g('hole'), 2)} |")
    out += ["\n## Where does the error come from? (reward model shared by A and B)\n",
            "On the held-out scenarios: MSE of the predicted ask score against the clean ask value, mean absolute error of the predicted "
            "act score against 1 − necessity (the act text carries no topic, so this error cannot be removed by seeing the combination), and "
            "the share of scenarios in which the sign of (ask − act) of the reward model matches the oracle (that is B's accuracy).\n",
            "| scenarios | condition | ask-score MSE | signed ask error (pred − true) | signed act error (pred − true) | act-score abs. error | B decision accuracy |", "|---|---|---|---|---|---|---|"]
    for c in masks:
        for cond in ("normal", "hole"):
            x = X[(X.combo == c) & (X.cond == cond)]
            out.append(f"| {names[c]} | {cond} | {ms(x.ask_mse, 4)} | {ms(x.ask_bias, 4)} | {ms(x.act_bias, 4)} | {ms(x.act_abs_err, 4)} | {ms(x.margin_sign_acc, 2)} |")
    flips = []
    for m in ("A", "B", "C"):
        fl = [np.mean(dec_store[("normal", s, m)] != dec_store[("hole", s, m)]) for s in B.SEEDS]
        flips.append(f"{m}: {np.mean(fl):.1%} (on all 60 scenarios, mean over seeds)")
    out.append("\nShare of the 60 decisions that differ between the normal and the hole model: " + "; ".join(flips) + ".\n")
    out += ["## Tabular agent: which level of the fallback chain decides (share of the 60 test scenarios)\n",
            "| condition | exact key | (topic, action) mean | global mean |", "|---|---|---|---|"]
    for cond in ("normal", "hole"):
        x = X[(X.combo == "all") & (X.cond == cond)]
        out.append(f"| {cond} | {x.c_exact.mean():.0%} | {x.c_topic.mean():.0%} | {x.c_global.mean():.0%} |")
    with open(os.path.join(RESULTS_DIR, "compositional.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
